CREATE TABLE CLIENTES (
    ID_CLIENTE      NUMBER(10)    NOT NULL,
    NOMBRE          VARCHAR2(100) NOT NULL,
    APELLIDO        VARCHAR2(100) NOT NULL,
    EMAIL           VARCHAR2(150) NOT NULL,
    TELEFONO        VARCHAR2(20),
    DIRECCION       VARCHAR2(300),
    FECHA_REGISTRO  DATE          DEFAULT SYSDATE,
    ESTADO          VARCHAR2(10)  DEFAULT 'ACTIVO',
    CONSTRAINT pk_clientes     PRIMARY KEY (ID_CLIENTE),
    CONSTRAINT uq_cli_email    UNIQUE (EMAIL),
    CONSTRAINT chk_cli_estado  CHECK (ESTADO IN ('ACTIVO','INACTIVO'))
);

CREATE TABLE VENDEDORES (
    ID_VENDEDOR     NUMBER(10)    NOT NULL,
    NOMBRE          VARCHAR2(100) NOT NULL,
    APELLIDO        VARCHAR2(100) NOT NULL,
    EMAIL           VARCHAR2(150) NOT NULL,
    TELEFONO        VARCHAR2(20),
    DESCRIPCION     VARCHAR2(500),
    CALIFICACION    NUMBER(3,2)   DEFAULT 0,
    FECHA_REGISTRO  DATE          DEFAULT SYSDATE,
    CONSTRAINT pk_vendedores   PRIMARY KEY (ID_VENDEDOR),
    CONSTRAINT uq_vnd_email    UNIQUE (EMAIL),
    CONSTRAINT chk_vnd_cal     CHECK (CALIFICACION BETWEEN 0 AND 5)
);

CREATE TABLE CATEGORIAS (
    ID_CATEGORIA  NUMBER(10)    NOT NULL,
    NOMBRE        VARCHAR2(100) NOT NULL,
    DESCRIPCION   VARCHAR2(500),
    CONSTRAINT pk_categorias PRIMARY KEY (ID_CATEGORIA),
    CONSTRAINT uq_cat_nombre UNIQUE (NOMBRE)
);

CREATE TABLE BODEGAS (
    ID_BODEGA   NUMBER(10)    NOT NULL,
    NOMBRE      VARCHAR2(100) NOT NULL,
    CIUDAD      VARCHAR2(100) NOT NULL,
    DIRECCION   VARCHAR2(300),
    ACTIVO      VARCHAR2(2)   DEFAULT 'SI',
    CONSTRAINT pk_bodegas      PRIMARY KEY (ID_BODEGA),
    CONSTRAINT chk_bod_activo  CHECK (ACTIVO IN ('SI','NO'))
);

CREATE TABLE METODOS_PAGO (
    ID_METODO    NUMBER(10)    NOT NULL,
    NOMBRE       VARCHAR2(50)  NOT NULL,
    DESCRIPCION  VARCHAR2(200),
    ACTIVO       VARCHAR2(2)   DEFAULT 'SI',
    CONSTRAINT pk_metodos_pago PRIMARY KEY (ID_METODO),
    CONSTRAINT uq_met_nombre   UNIQUE (NOMBRE),
    CONSTRAINT chk_met_activo  CHECK (ACTIVO IN ('SI','NO'))
);

CREATE TABLE PRODUCTOS (
    ID_PRODUCTO   NUMBER(10)     NOT NULL,
    NOMBRE        VARCHAR2(200)  NOT NULL,
    DESCRIPCION   VARCHAR2(1000),
    PRECIO        NUMBER(12,2)   NOT NULL,
    ID_VENDEDOR   NUMBER(10)     NOT NULL,
    ID_CATEGORIA  NUMBER(10)     NOT NULL,
    CONSTRAINT pk_productos    PRIMARY KEY (ID_PRODUCTO),
    CONSTRAINT chk_prod_precio CHECK (PRECIO > 0)
);

CREATE TABLE INVENTARIO (
    ID_INVENTARIO       NUMBER(10) NOT NULL,
    ID_PRODUCTO         NUMBER(10) NOT NULL,
    ID_BODEGA           NUMBER(10) NOT NULL,
    CANTIDAD            NUMBER(10) DEFAULT 0,
    STOCK_MINIMO        NUMBER(10) DEFAULT 5,
    FECHA_ACTUALIZACION DATE       DEFAULT SYSDATE,
    CONSTRAINT pk_inventario      PRIMARY KEY (ID_INVENTARIO),
    CONSTRAINT uq_inv_prod_bodega UNIQUE (ID_PRODUCTO, ID_BODEGA),
    CONSTRAINT chk_inv_cantidad   CHECK (CANTIDAD >= 0)
);

CREATE TABLE PEDIDOS (
    ID_PEDIDO     NUMBER(10)   NOT NULL,
    ID_CLIENTE    NUMBER(10)   NOT NULL,
    FECHA_PEDIDO  DATE         DEFAULT SYSDATE,
    ESTADO        VARCHAR2(20) DEFAULT 'PENDIENTE',
    CONSTRAINT pk_pedidos     PRIMARY KEY (ID_PEDIDO),
    CONSTRAINT chk_ped_estado CHECK (ESTADO IN ('PENDIENTE','CONFIRMADO','ENVIADO','ENTREGADO','CANCELADO'))
);

CREATE TABLE DETALLE_PEDIDOS (
    ID_DETALLE       NUMBER(10)   NOT NULL,
    ID_PEDIDO        NUMBER(10)   NOT NULL,
    ID_PRODUCTO      NUMBER(10)   NOT NULL,
    CANTIDAD         NUMBER(10)   NOT NULL,
    PRECIO_UNITARIO  NUMBER(12,2) NOT NULL,
    CONSTRAINT pk_detalle    PRIMARY KEY (ID_DETALLE),
    CONSTRAINT chk_det_cant  CHECK (CANTIDAD > 0),
    CONSTRAINT chk_det_pre   CHECK (PRECIO_UNITARIO > 0)
);

CREATE TABLE PAGOS (
    ID_PAGO      NUMBER(10)   NOT NULL,
    ID_PEDIDO    NUMBER(10)   NOT NULL,
    ID_METODO    NUMBER(10)   NOT NULL,
    FECHA_PAGO   DATE         DEFAULT SYSDATE,
    MONTO        NUMBER(14,2) NOT NULL,
    ESTADO       VARCHAR2(20) DEFAULT 'PENDIENTE',
    CONSTRAINT pk_pagos        PRIMARY KEY (ID_PAGO),
    CONSTRAINT chk_pago_monto  CHECK (MONTO > 0),
    CONSTRAINT chk_pago_estado CHECK (ESTADO IN ('PENDIENTE','COMPLETADO','RECHAZADO','REEMBOLSADO'))
);

CREATE TABLE ENVIOS (
    ID_ENVIO            NUMBER(10)    NOT NULL,
    ID_PEDIDO           NUMBER(10)    NOT NULL,
    DIRECCION_ENVIO     VARCHAR2(300) NOT NULL,
    FECHA_ENVIO         DATE,
    FECHA_ENTREGA_EST   DATE,
    FECHA_ENTREGA_REAL  DATE,
    ESTADO              VARCHAR2(20)  DEFAULT 'PREPARANDO',
    NUM_SEGUIMIENTO     VARCHAR2(50),
    CONSTRAINT pk_envios      PRIMARY KEY (ID_ENVIO),
    CONSTRAINT chk_env_estado CHECK (ESTADO IN ('PREPARANDO','EN_CAMINO','ENTREGADO','DEVUELTO'))
);

CREATE TABLE DEVOLUCIONES (
    ID_DEVOLUCION    NUMBER(10)   NOT NULL,
    ID_PEDIDO        NUMBER(10)   NOT NULL,
    ID_PRODUCTO      NUMBER(10)   NOT NULL,
    FECHA_DEVOLUCION DATE         DEFAULT SYSDATE,
    MOTIVO           VARCHAR2(500),
    ESTADO           VARCHAR2(20) DEFAULT 'SOLICITADA',
    MONTO_REEMBOLSO  NUMBER(14,2) DEFAULT 0,
    CONSTRAINT pk_devoluciones PRIMARY KEY (ID_DEVOLUCION),
    CONSTRAINT chk_dev_estado  CHECK (ESTADO IN ('SOLICITADA','APROBADA','RECHAZADA','COMPLETADA'))
);

